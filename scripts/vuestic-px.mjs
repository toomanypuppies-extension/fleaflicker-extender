// Writes src/styles/vuestic-px.css: vuestic's rem sizes restated in px, for the components we use.
//
// Vuestic sizes its components in rem. Fleaflicker's page sets the root font size to 10px, so in the
// extension everything vuestic draws comes out at 10/16 the intended size. In px (1rem = 16px) they
// look the same on the standalone site and on fleaflicker.
//
// Run with `yarn vuestic-px` after upgrading vuestic or registering another component in main.js.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Component stylesheets in vuestic-ui/dist/es whose names start with these
const COMPONENTS = [
  'VaBadge', 'VaButton', 'VaCard', 'VaCheckbox', 'VaChip', 'VaDropdown', 'VaIcon', 'VaInnerLoading',
  'VaInput', 'VaMessageList', 'VaModal', 'VaSelect', 'VaTab',
];
const ROOT_PX = 16;

const distDir = fileURLToPath(new URL('../node_modules/vuestic-ui/dist/es/', import.meta.url));
const outFile = fileURLToPath(new URL('../src/styles/vuestic-px.css', import.meta.url));

const toPx = (value) => value.replace(/(-?\d*\.?\d+)rem\b/g, (match, number) => `${+(parseFloat(number) * ROOT_PX).toFixed(3)}px`);

const variables = new Map();
const rules = [];

const files = [
  // Shared variables like gaps and border widths
  '../styles/css-variables.css',
  ...readdirSync(distDir)
    .filter(file => file.endsWith('.css') && COMPONENTS.some(name => file.startsWith(name)))
    .sort(),
];

for (const file of files) {
  const css = readFileSync(distDir + file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const [, selector, body] of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const declarations = body.split(';').map(d => d.trim()).filter(d => /\d\s*rem\b/.test(d));
    if (declarations.length === 0) continue;

    const trimmed = selector.trim();
    if (/^(:root|:host)/.test(trimmed)) {
      declarations
        .filter(d => d.startsWith('--va-'))
        .forEach(d => {
          const [name, ...value] = d.split(':');
          variables.set(name.trim(), toPx(value.join(':').trim()));
        });
    } else if (!trimmed.startsWith('@')) {
      // html raises specificity above vuestic's own rule
      const scoped = trimmed.split(',').map(part => `html ${part.trim()}`).join(', ');
      rules.push(`${scoped} {\n${declarations.map(d => `  ${toPx(d)};`).join('\n')}\n}`);
    }
  }
}

const output = `/*
 * Generated by scripts/vuestic-px.mjs from vuestic-ui ${JSON.parse(readFileSync(new URL('../node_modules/vuestic-ui/package.json', import.meta.url))).version}, don't edit.
 * Vuestic's rem sizes in px, so its components are the same size on fleaflicker's page (10px root).
 */

html:root {
${[...variables].map(([name, value]) => `  ${name}: ${value};`).join('\n')}
}

${rules.join('\n\n')}
`;

writeFileSync(outFile, output);
console.log(`Wrote ${variables.size} variables and ${rules.length} rules to ${outFile}`);
